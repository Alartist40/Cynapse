//! Built-in TUI color themes.
//!
//! Each theme defines a palette of named colors used throughout the interface.
//! The active theme is selected via `tui.theme` in `~/.cynapse/config.yaml`.

use ratatui::style::Color;

#[derive(Debug, Clone)]
pub struct Theme {
    pub name: &'static str,
    pub gold: Color,
    pub accent: Color,
    pub dim: Color,
    pub bright: Color,
    pub bg: Color,
    pub border: Color,
    pub user: Color,
    pub assistant: Color,
    pub thinking: Color,
    pub system: Color,
    pub tool: Color,
    pub error: Color,
    pub success: Color,
    pub highlight_bg: Color,
}

impl Theme {
    pub fn by_name(name: &str) -> Self {
        match name.to_lowercase().as_str() {
            "tokyonight" | "tokyo-night" => TOKYO_NIGHT,
            "catppuccin" => CATPPUCCIN,
            "catppuccin-macchiato" => CATPPUCCIN_MACCHIATO,
            "dracula" => DRACULA,
            "nord" => NORD,
            "gruvbox" => GRUVBOX,
            "one-dark" | "onedark" => ONE_DARK,
            "rose-pine" | "rosepine" => ROSE_PINE,
            "everforest" => EVERFOREST,
            "kanagawa" => KANAGAWA,
            "solarized" => SOLARIZED,
            "flexoki" => FLEXOKI,
            "monokai" => MONOKAI,
            "cobalt2" => COBALT2,
            "ayu" => AYU,
            _ => DEFAULT_THEME,
        }
    }

    pub fn all_names() -> &'static [&'static str] {
        &[
            "default",
            "tokyonight",
            "catppuccin",
            "catppuccin-macchiato",
            "dracula",
            "nord",
            "gruvbox",
            "one-dark",
            "rose-pine",
            "everforest",
            "kanagawa",
            "solarized",
            "flexoki",
            "monokai",
            "cobalt2",
            "ayu",
        ]
    }
}

