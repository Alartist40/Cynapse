//! Built-in TUI color themes with 22 semantic roles.
//!
//! Inspired by jcode's palette architecture: every color is a named semantic
//! role (User, Ai, Accent, etc.), not a raw hex value. This ensures visual
//! consistency across all UI surfaces.

use ratatui::style::Color;

/// Semantic color roles — every color in the TUI maps to one of these.
#[derive(Debug, Clone)]
pub struct Theme {
    pub name: &'static str,
    // ── Core roles ──────────────────────────────────────────────
    pub user: Color,           // User messages, prompt labels
    pub ai: Color,             // AI/assistant responses
    pub accent: Color,         // Purple/highlight accent (borders, links)
    pub dim: Color,            // Dimmed/secondary text
    pub bright: Color,         // Primary bright text
    pub bg: Color,             // Terminal background hint
    // ── Message roles ───────────────────────────────────────────
    pub thinking: Color,       // Reasoning/scratchpad output
    pub system: Color,         // System messages, notifications
    pub tool: Color,           // Tool call labels, function names
    pub file_link: Color,      // File paths, clickable links
    // ── Status roles ────────────────────────────────────────────
    pub error: Color,          // Errors, failures
    pub success: Color,        // Success, completion
    pub warning: Color,        // Warnings, caution
    pub info: Color,           // Informational messages
    pub queued: Color,         // Queued/pending items
    // ── UI chrome roles ─────────────────────────────────────────
    pub border: Color,         // Default border color
    pub border_focus: Color,   // Border when panel is focused
    pub header_icon: Color,    // Header icon color
    pub header_name: Color,    // Header title/name
    pub selection_bg: Color,   // Selection background
    pub highlight_bg: Color,   // Highlight/background accent
    // ── Backward compat aliases (used by existing code) ─────────
    pub gold: Color,           // Alias for user/header accent
}

impl Theme {
    pub fn by_name(name: &str) -> Self {
        match name.to_lowercase().as_str() {
            "tokyonight" | "tokyo-night" => TOKYO_NIGHT,
            "catppuccin" => CATPPUCCIN,
            "catppuccin-macchiato" => CATPPUCCIN_MACCHIATO,
            "dracula" => DRACULA,
            "nord" => NORD,
            "gruvbox" => GRUVBOX,
            "one-dark" | "onedark" => ONE_DARK,
            "rose-pine" | "rosepine" => ROSE_PINE,
            "everforest" => EVERFOREST,
            "kanagawa" => KANAGAWA,
            "solarized" => SOLARIZED,
            "flexoki" => FLEXOKI,
            "monokai" => MONOKAI,
            "cobalt2" => COBALT2,
            "ayu" => AYU,
            _ => DEFAULT_THEME,
        }
    }

    pub fn all_names() -> &'static [&'static str] {
        &[
            "default",
            "tokyonight",
            "catppuccin",
            "catppuccin-macchiato",
            "dracula",
            "nord",
            "gruvbox",
            "one-dark",
            "rose-pine",
            "everforest",
            "kanagawa",
            "solarized",
            "flexoki",
            "monokai",
            "cobalt2",
            "ayu",
        ]
    }
}

